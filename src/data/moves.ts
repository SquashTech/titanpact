// Ancient (2026-09-17) as the enemy's own vocabulary. A move whose whole payload is its riders is
// kind 'buff' whatever it does to the enemy — the UI derives the Debuff label
// from the payload (MoveTile isDebuff).
//
// `tier` is the designer table's Early/Mid/Late column: it gates level-up offers
// (src/run/progression.ts bandRank) and nothing in combat reads it.
// Omitted reads as Early; every slate carries a tier, Class and signature moves none (test/moveTiers.test.ts).
//
// LATE-TIER MANA WAS RE-PRICED x0.75 on 2026-09-13 (XP Overhaul phase 6, per user direction:
// "a lot more than 4.5% of casts should be lategame moves"), rounded to 5 with a floor of 45; the
// seven moves priced at 100+ — Overdrive, Pack Leader and the other whole-pool casts — keep their
// authored price. Measured, a Late move at 70+ against a 50-95 pool plus 10 a round was cast ONCE
// a fight and then the hero filled with Early; at 55-60 a hero affords it twice, which took Late
// from 11% of Act 4 casts to 19% and the finale from 23% to 36% (docs/xp-overhaul.md §8).
// The runbook's convention that 70+ means Late is therefore 45+ now (docs/authoring-moves.md).
//
// PUSHED PART-WAY BACK on 2026-09-17 (per user direction — mana had become trivial, and a spread
// hit was two hits for one price): every Late move under 100 +10, every SPREAD damage move a
// further +10 at Late (+20 in all) and +15 at Mid, so a spread Late hit sits at 65-80 against a
// single one at 55-70. Measured (2000 runs, both sides pay): Late casts 2.2 -> 1.6 a fight in Act
// 5, spread and single within 5.6-8.0 and 4.7-6.9 damage a mana (spread had been 10-12 against
// 4-6), full clear 57 -> 62% because the enemy AI does not manage mana and its Late kits thin out
// faster than the pilot's. The Late convention is 55+ now, a spread Late 65+.

